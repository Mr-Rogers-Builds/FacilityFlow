CREATE TABLE location_nodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    location_type_id BIGINT NOT NULL,
    parent_id BIGINT,
    name VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    archived_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_site_id FOREIGN KEY (site_id) REFERENCES sites(id),
    CONSTRAINT fk_location_type_id FOREIGN KEY (location_type_id) REFERENCES location_types(id),
    CONSTRAINT fk_parent_id FOREIGN KEY (parent_id) REFERENCES location_nodes(id)
);
CREATE INDEX idx_location_nodes_site_id ON location_nodes(site_id);
CREATE INDEX idx_location_nodes_location_type_id ON location_nodes(location_type_id);
CREATE INDEX idx_location_nodes_parent_id ON location_nodes(parent_id);